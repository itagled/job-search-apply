#!/usr/bin/env python3
"""Replaces the attached CV of already-created Gmail drafts with each company's custom CV.

For each ``application_contact`` with ``gmail_draft_id`` and status ``to_schedule``/``draft``:
looks for ``profile/cv/companies/<CV_FILE_PREFIX>_<Company>.pdf`` (same name generated by
jobradar/cv/gdrive_cv.py), updates ``cv_file`` and rewrites the draft (``drafts.update``) with the
same recipient, subject and body. Sends nothing.

    jobradar refresh-drafts [--dry-run]
"""

from __future__ import annotations

import argparse
import json
import logging

from sqlalchemy import select

from jobradar import config
from jobradar.cv.gdrive_cv import OUT_DIR, safe_company
from jobradar.db.models import ApplicationContact as C
from jobradar.db.session import SessionLocal
from jobradar.gapi import gmail
from jobradar.outreach.send_outreach import update_contact

log = logging.getLogger(__name__)


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--dry-run", action="store_true")
    args = ap.parse_args(argv)
    s = SessionLocal()
    rows = (
        s.execute(
            select(
                C.id, C.company, C.email, C.email_subject, C.email_body, C.cv_file, C.gmail_draft_id, C.outreach_status
            )
            .where(C.gmail_draft_id.is_not(None), C.outreach_status.in_(("to_schedule", "draft")))
            .order_by(C.id)
        )
        .mappings()
        .all()
    )
    svc = None if args.dry_run else gmail.service()
    done, missing = 0, []
    for r in rows:
        pdf = OUT_DIR / f"{config.get('CV_FILE_PREFIX')}_{safe_company(r['company'])}.pdf"
        if not pdf.is_file():
            # no custom CV yet: corrected master of the same language (never the old CV)
            lang = "ES" if "_ES" in (r["cv_file"] or "") else "EN"
            pdf = config.ROOT / "profile" / "cv" / f"{config.get('CV_FILE_PREFIX')}_{lang}.pdf"
            missing.append(r["company"])
        rel = str(pdf.relative_to(config.ROOT)).replace("\\", "/")
        if args.dry_run:
            log.info("[dry] [%s] %s: %s -> %s", r["id"], r["company"], r["cv_file"], rel)
            continue
        msg = gmail.build_message(r["email"], r["email_subject"], r["email_body"], attachments=[pdf])
        res = (
            svc.users()
            .drafts()
            .update(userId="me", id=r["gmail_draft_id"], body={"id": r["gmail_draft_id"], "message": msg})
            .execute()
        )
        update_contact(s, r["id"], cv_file=rel, gmail_message_id=(res.get("message") or {}).get("id"))
        s.commit()
        done += 1
        log.info("[%s] %s: draft updated with %s", r["id"], r["company"], pdf.name)
    s.close()
    print(json.dumps({"updated": done, "missing_tailored_cv": sorted(set(missing))}, ensure_ascii=False))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
